use std::collections::HashMap;
use serde::Deserialize;

#[derive(Debug, Deserialize, Default, Clone)]
struct Manifest {
    name: Option<String>,
    version: Option<String>,
    theme: Option<ThemeTable>,
    tokens: Option<HashMap<String, String>>,
}

#[derive(Debug, Deserialize, Default, Clone)]
struct ThemeTable {
    tokens: Option<HashMap<String, String>>,
}

#[derive(Debug, Deserialize, Default, Clone)]
pub struct TokenSet {
    #[serde(default)]
    pub tokens: HashMap<String, String>,
}

impl TokenSet {
    /// Parses a TokenSet from TOML string, supporting either `[theme.tokens]` or `[tokens]`.
    pub fn from_toml(content: &str) -> Result<Self, toml::de::Error> {
        if let Ok(manifest) = toml::from_str::<Manifest>(content) {
            let mut tokens = HashMap::new();
            if let Some(t) = manifest.tokens {
                tokens.extend(t);
            }
            if let Some(theme) = manifest.theme {
                if let Some(t) = theme.tokens {
                    tokens.extend(t);
                }
            }
            if !tokens.is_empty() || manifest.name.is_some() {
                return Ok(Self { tokens });
            }
        }
        toml::from_str::<TokenSet>(content)
    }
    /// Retrieve a token value by name. Returns `None` if the token is not defined.
    pub fn get(&self, name: &str) -> Option<&str> {
        self.tokens.get(name).map(|s| s.as_str())
    }

    /// Returns an iterator over `(name, value)` pairs.
    pub fn iter(&self) -> impl Iterator<Item = (&String, &String)> {
        self.tokens.iter()
    }

    /// Compiles all tokens in this set into CSS custom properties (`:root { --ts-key: val; }`).
    pub fn compile_css(&self) -> String {
        let mut out = String::from("/* Generated by Tessera Design Token Compiler */\n:root {\n");
        let mut sorted_tokens: Vec<_> = self.tokens.iter().collect();
        sorted_tokens.sort_by_key(|(k, _)| (*k).clone());
        for (key, val) in sorted_tokens {
            let css_var = key.replace('_', "-");
            out.push_str(&format!("  --ts-{}: {};\n", css_var, val));
        }
        out.push_str("}\n");
        out
    }
}
