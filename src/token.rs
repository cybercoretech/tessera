use serde::Deserialize;
use std::{collections::HashMap, error::Error};

#[derive(Debug, Deserialize, Default, Clone)]
pub struct TokenSet {
    #[serde(default)]
    pub tokens: HashMap<String, String>,
}

impl TokenSet {
    /// Parses a TokenSet from TOML string, supporting either `[theme.tokens]` or `[tokens]`.
    pub fn from_toml(content: &str) -> Result<Self, Box<dyn Error + Send + Sync>> {
        let config = tessera_config::ProjectConfig::parse(content)?;
        let tokens = config
            .theme_tokens()
            .iter()
            .map(|(key, value)| (key.clone(), value.clone()))
            .collect();
        Ok(Self { tokens })
    }
    /// Retrieve a token value by name. Returns `None` if the token is not defined.
    pub fn get(&self, name: &str) -> Option<&str> {
        self.tokens.get(name).map(|s| s.as_str())
    }

    /// Returns an iterator over `(name, value)` pairs.
    pub fn iter(&self) -> impl Iterator<Item = (&String, &String)> {
        self.tokens.iter()
    }

    /// Compiles all tokens in this set into CSS custom properties (`:root { --ts-key: val; }`).
    pub fn compile_css(&self) -> String {
        let mut out = String::from("/* Generated by Tessera Design Token Compiler */\n:root {\n");
        for (css_var, val) in self.sorted_tokens() {
            out.push_str(&format!("  --ts-{css_var}: {val};\n"));
        }
        out.push_str("}\n");
        out
    }

    /// Compiles tokens into Sass variables and a map for downstream theme use.
    #[allow(dead_code)] // Consumed by the planned standalone Sass-token export.
    pub fn compile_scss(&self) -> String {
        let tokens = self.sorted_tokens();
        let mut out = String::from("// Generated by Tessera Design Token Compiler\n");
        for (name, value) in &tokens {
            out.push_str(&format!("$ts-{name}: {value};\n"));
        }
        out.push_str("\n$ts-tokens: (\n");
        for (name, _) in tokens {
            out.push_str(&format!("  \"{name}\": $ts-{name},\n"));
        }
        out.push_str(");\n");
        out
    }

    fn sorted_tokens(&self) -> Vec<(String, String)> {
        let mut tokens: Vec<_> = self
            .tokens
            .iter()
            .map(|(key, value)| (key.replace('_', "-"), value.clone()))
            .collect();
        tokens.sort_by(|left, right| left.0.cmp(&right.0));
        tokens
    }
}
