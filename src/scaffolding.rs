use std::fs;
use std::path::Path;

/// Scaffolds a fresh Tessera project in a subdirectory.
pub fn create_project(name: &str) -> Result<(), Box<dyn std::error::Error + Send + Sync>> {
    let project_dir = Path::new(name);
    if project_dir.exists() {
        return Err(format!("Directory '{name}' already exists").into());
    }
    // Create directory structure
    let dirs = [
        project_dir.join("content"),
        project_dir.join("dist"),
        project_dir.join("layouts"),
        project_dir.join("templates"),
        project_dir.join("styles"),
        project_dir.join("scripts"),
        project_dir.join("public"),
        project_dir.join("src").join("components"),
    ];
    for d in dirs.iter() {
        fs::create_dir_all(d)?;
    }

    // Provide a TypeScript entry point without enabling JavaScript output by default.
    let script_path = project_dir.join("scripts").join("main.ts");
    let script_content =
        "// Enable scripts in tessera.toml to bundle this entry point.\nconsole.log('⚡ Tessera site initialized');\n";
    fs::write(script_path, script_content)?;

    // Give the project a stylesheet of its own; the build appends it after the Kit.
    let style_path = project_dir.join("styles").join("main.css");
    let style_content = "/* Your site's styles. `tessera build` adds this file to dist/styles.css
   after the Tessera Kit. Use the --ts-* tokens from tessera.toml so a token
   change restyles your own rules too. */

body {
  font-family: var(--ts-font-main, system-ui, sans-serif);
}

::selection {
  background: var(--ts-primary);
  color: #ffffff;
}
";
    fs::write(style_path, style_content)?;

    // Write a minimal tessera.toml
    let toml_path = project_dir.join("tessera.toml");
    let toml_content = format!(
        "name = \"{name}\"\nversion = \"0.1.0\"\n\n[theme.tokens]\nprimary = \"#0066ff\"\nsecondary = \"#ff6600\"\nfont-main = \"system-ui, sans-serif\"\n\n[style]\nsource = \"css\"\nsass_compiler = \"grass\"\n\n[scripts]\nenabled = false\nentry_points = [\"scripts/main.ts\"]\ntypecheck = false\ninteractions = false\n"
    );
    fs::write(toml_path, toml_content)?;

    // Write base HTML layout
    let layout_path = project_dir.join("layouts").join("base.html");
    let layout_content = r#"<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{{title}}</title>
  <meta name="description" content="{{description}}">
  <link rel="stylesheet" href="/styles.css">
</head>
<body>
  <header style="border-bottom: 1px solid var(--ts-border-color, #e5e7eb);">
    <div class="ts-container">
      <nav class="ts-nav">
        <a href="/" style="font-weight: 700; font-size: 1.25rem;">⚡ Tessera</a>
        <div style="display: flex; align-items: center; gap: 1rem;">
          <ul class="ts-nav__links">
            <li><a href="/">Home</a></li>
          </ul>
        </div>
      </nav>
    </div>
  </header>
  <main class="ts-container ts-section">
    {{content}}
  </main>
  <footer class="ts-section" style="border-top: 1px solid var(--ts-border-color, #e5e7eb); margin-top: 4rem; padding-top: 1.5rem; padding-bottom: 1.5rem;">
    <div class="ts-container" style="color: #6b7280; font-size: 0.875rem;">
      Built with <a href="https://github.com/cybercoretech/tessera">Tessera</a>
    </div>
  </footer>
</body>
</html>
"#;
    fs::write(layout_path, layout_content)?;

    // Write a simple page template
    let template_path = project_dir.join("templates").join("page.md");
    let template_content = "---\ntitle: {{title}}\ndescription: \nlayout: base\n---\n# {{title}}\n\nWrite your content here.\n";
    fs::write(template_path, template_content)?;

    // Create an initial index markdown page with front matter
    let index_path = project_dir.join("content").join("index.md");
    let index_content = format!(
        "---\ntitle: Welcome to {name}\ndescription: Static site built with Tessera\nlayout: base\n---\n# Welcome to {name}\n\nThis is the homepage generated by `tessera new`.\n\n<a class=\"ts-button\" href=\"#\">Get Started</a>\n"
    );
    fs::write(index_path, index_content)?;

    println!("Created new Tessera project in directory '{name}'.");
    Ok(())
}
